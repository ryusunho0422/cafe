/**
 * 접수된 실제 주문 객체를 Supabase INSERT SQL 문자열로 변환하는 유틸리티 함수
 */
export function generateOrderInsertSql(order: {
  customerName: string;
  phoneNumber: string;
  beverageName: string;
  beveragePrice: number;
  size: string;
  sizePrice: number;
  selectedOptionsText: string[];
  extraOptionsPrice: number;
  quantity: number;
  totalPrice: number;
  requestMemo: string;
}): string {
  const optionsArrayString = order.selectedOptionsText.length > 0
    ? `ARRAY[${order.selectedOptionsText.map(opt => `'${opt}'`).join(', ')}]`
    : `ARRAY[]::TEXT[]`;

  return `INSERT INTO cafe_menu (
    customer_name,
    phone_number,
    beverage_name,
    beverage_price,
    size,
    size_price,
    options,
    options_price,
    quantity,
    total_price,
    request_memo
) VALUES (
    '${order.customerName.replace(/'/g, "''")}',
    '${order.phoneNumber.replace(/'/g, "''")}',
    '${order.beverageName.replace(/'/g, "''")}',
    ${order.beveragePrice},
    '${order.size}',
    ${order.sizePrice},
    ${optionsArrayString},
    ${order.extraOptionsPrice},
    ${order.quantity},
    ${order.totalPrice},
    ${order.requestMemo ? `'${order.requestMemo.replace(/'/g, "''")}'` : 'NULL'}
);`;
}
